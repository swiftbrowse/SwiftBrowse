"""Generates swiftbrowse/_generated.py from the engine's own schemas
(`swiftbrowse sdk --schema`), so the SDK can't drift from the engine.

Usage: python scripts/generate.py [path-to-swiftbrowse]
"""

import json
import os
import subprocess
import sys
import textwrap

here = os.path.dirname(os.path.abspath(__file__))
binary = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SWIFTBROWSE_BIN", "swiftbrowse")
spec = json.loads(subprocess.check_output([binary, "sdk", "--schema"]))

PY_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "array": "list", "object": "dict"}


def py_type(schema, defs=None):
    defs = defs or {}
    if not isinstance(schema, dict):
        return "Any"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        target = defs.get(name, {})
        # Enums (plain or as a union of constants) are strings.
        variants = target.get("oneOf") or target.get("anyOf") or []
        if "enum" in target or (variants and all("const" in v for v in variants)):
            return "str"
        return py_type(target, defs) if target else "dict"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = [py_type(s, defs) for s in schema[key] if s.get("type") != "null"]
            parts = list(dict.fromkeys(parts))
            return parts[0] if len(parts) == 1 else f"Union[{', '.join(parts)}]"
    if "enum" in schema or "const" in schema:
        return "str"
    if "oneOf" not in schema and "anyOf" not in schema and schema.get("properties") is None and schema.get("type") is None:
        return "Any"
    types = schema.get("type")
    if isinstance(types, list):
        types = [t for t in types if t != "null"]
        types = types[0] if len(types) == 1 else None
    if types == "array":
        return f"List[{py_type(schema.get('items', {}), defs)}]"
    return PY_TYPES.get(types, "Any")


lines = [
    '"""Generated by scripts/generate.py from `swiftbrowse sdk --schema`. Do not edit."""',
    "",
    "from typing import Any, List, Optional, Union",
    "",
    f"PROTOCOL = {spec['protocol']}",
    "",
    "",
    "class Operations:",
    '    """One method per engine operation: required arguments in order, the rest by keyword."""',
    "",
    "    def run(self, op: str, args: dict) -> dict:  # implemented by Session",
    "        raise NotImplementedError",
    "",
]
for op in spec["ops"]:
    schema = op["schema"]
    props = schema.get("properties", {})
    required = schema.get("required", [])
    params = ["self"]
    for name in required:
        params.append(f"{name}: {py_type(props[name], schema.get('$defs'))}")
    optional = [n for n in props if n not in required]
    if optional:
        params.append("*")
        for name in optional:
            params.append(f"{name}: Optional[{py_type(props[name], schema.get('$defs'))}] = None")
    lines.append(f"    def {op['name']}({', '.join(params)}) -> dict:")
    doc = "\n".join(textwrap.wrap(op["description"], 88))
    lines.append(textwrap.indent(f'"""{doc}"""', " " * 8))
    names = required + optional
    lines.append(f"        return self.run({op['name']!r}, _args(locals(), {names!r}))")
    lines.append("")
lines += [
    "",
    "def _args(scope: dict, names: list) -> dict:",
    "    return {n: scope[n] for n in names if scope[n] is not None}",
    "",
]
with open(os.path.join(here, "..", "swiftbrowse", "_generated.py"), "w") as f:
    f.write("\n".join(lines))
print(f"generated {len(spec['ops'])} operations")
