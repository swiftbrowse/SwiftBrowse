// Generates the SDK's operation table and TypeScript types from the engine's own
// schemas (`swiftbrowse sdk --schema`), so the SDK can't drift from the engine.
//
// Usage: node scripts/generate.mjs [path-to-swiftbrowse]

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const bin = process.argv[2] || process.env.SWIFTBROWSE_BIN || 'swiftbrowse';
const { protocol, ops } = JSON.parse(execFileSync(bin, ['sdk', '--schema']).toString());

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const doc = (text, indent = '') => (text ? `${indent}/** ${text.trim().replace(/\*\//g, '*\\/').replace(/\n/g, `\n${indent} * `)} */\n` : '');
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

const defs = new Map();
/** JSON Schema -> TypeScript type expression. */
function ts(schema, indent = '') {
  if (schema === true || !schema || Object.keys(schema).length === 0) return 'unknown';
  if (schema.$ref) return schema.$ref.split('/').pop();
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  const union = schema.oneOf || schema.anyOf;
  let base = null;
  if (union) {
    const parts = union.filter((s) => s.type !== 'null').map((s) => ts(s, indent));
    base = parts.length > 1 ? parts.map((p) => (p.includes('\n') || p.includes('&') ? `(${p})` : p)).join(' | ') : parts[0];
    if (!schema.properties) return base;
  }
  const types = [].concat(schema.type || (schema.properties ? 'object' : [])).filter((t) => t !== 'null');
  if (types.length > 1) return types.map((t) => ts({ ...schema, type: t }, indent)).join(' | ');
  switch (types[0]) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `${wrap(ts(schema.items, indent))}[]`;
    case 'object': {
      const props = schema.properties || {};
      if (!Object.keys(props).length && schema.additionalProperties && schema.additionalProperties !== false) {
        return `Record<string, ${ts(schema.additionalProperties, indent)}>`;
      }
      const required = new Set(schema.required || []);
      const lines = Object.entries(props).map(([k, v]) =>
        `${doc(v.description, indent + '  ')}${indent}  ${key(k)}${required.has(k) ? '' : '?'}: ${ts(v, indent + '  ')};`);
      const obj = `{\n${lines.join('\n')}\n${indent}}`;
      return base ? `(${base}) & ${obj}` : obj;
    }
    default: return 'unknown';
  }
}
const wrap = (t) => (/[|&\s]/.test(t) ? `(${t})` : t);

let types = '';
const table = [];
for (const op of ops) {
  for (const [name, def] of Object.entries(op.schema.$defs || {})) {
    if (!defs.has(name)) defs.set(name, `${doc(def.description)}export type ${name} = ${ts(def)};\n`);
  }
  const argsName = `${pascal(op.name)}Args`;
  const required = op.schema.required || [];
  const props = op.schema.properties || {};
  types += `${doc(op.description)}export type ${argsName} = ${Object.keys(props).length ? ts({ ...op.schema, $defs: undefined, description: undefined }) : 'Record<string, never>'};\n`;
  table.push({ op: op.name, method: camel(op.name), positional: required, description: op.description, argsName, props, required });
}

// Methods: required arguments positionally (in schema order), the rest as options.
let methods = '';
for (const t of table) {
  const params = t.positional.map((p) => `${camel(p)}: ${t.argsName}[${JSON.stringify(p)}]`);
  const optional = Object.keys(t.props).filter((p) => !t.required.includes(p));
  if (optional.length) params.push(`options?: Omit<${t.argsName}, ${t.positional.map((p) => JSON.stringify(p)).join(' | ') || 'never'}>`);
  methods += `${doc(t.description, '  ')}  ${t.method}(${params.join(', ')}): Promise<ActionResult>;\n`;
}

const header = `// Generated by scripts/generate.mjs from \`swiftbrowse sdk --schema\`. Do not edit.\n\n`;
fs.writeFileSync(path.join(here, '../src/ops.generated.js'),
  `${header}export const PROTOCOL = ${protocol};\n\n/** [operation, method name, positional argument names] */\nexport const OPS = ${JSON.stringify(table.map((t) => [t.op, t.method, t.positional]), null, 0).replace(/\],\[/g, '],\n  [').replace(/^\[\[/, '[\n  [').replace(/\]\]$/, '],\n]')};\n`);
fs.writeFileSync(path.join(here, '../src/ops.generated.d.ts'),
  `${header}import type { ActionResult } from './index.js';\n\n${[...defs.values()].join('\n')}\n${types}\n/** One method per engine operation. */\nexport interface Operations {\n${methods}}\n`);
console.log(`generated ${table.length} operations, ${defs.size} shared types`);
